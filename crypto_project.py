def make_report(app_name, purpose, requested, needed):
    profile = {
        "purpose": purpose,
        "requested": set(requested or []),
        "needed": set(needed or []),
    }

    result = analyze_app(app_name, profile)

    report = {
        "app": result["app"],
        "purpose": result["purpose"],
        "risk_level": result["level"],
        "risk_score": result["score"],
        "requested_permissions": sorted(result["requested"]),
        "excessive_permissions": sorted(result["excessive"]),
        "least_privilege_recommendation": sorted(result["recommended"]),
    }
    return result, report


def load_profile(app_name):
    profile = APP_PROFILES[app_name]
    requested = [
        permission for permission in PERMISSION_RISK
        if permission in profile["requested"]
    ]
    needed = [
        permission for permission in PERMISSION_RISK
        if permission in profile["needed"]
    ]
    return profile["purpose"], requested, needed


def analyze_from_gui(app_name, purpose, requested, needed):
    result, report = make_report(app_name, purpose, requested, needed)

    bar = "█" * round(result["score"] / 10)
    bar += "░" * (10 - len(bar))

    risk_view = f"""
## {result["level"]} risk · {result["score"]}/100

`{bar}`

**Excessive requests:** {len(result["excessive"])}
**Least-privilege permissions:** {len(result["recommended"])}

The score combines permission sensitivity with extra points for requests
outside the stated app purpose. It is a classroom heuristic, not proof of malware.
"""

    details = {
        "App": result["app"],
        "Stated purpose": result["purpose"],
        "Requested permissions": sorted(result["requested"]),
        "Needed permissions": sorted(result["needed"]),
        "Excessive requests": sorted(result["excessive"]),
        "Least-privilege recommendation": sorted(result["recommended"]),
        "Score breakdown": {
            "Sensitivity points": result["sensitivity_points"],
            "Purpose-mismatch points": result["mismatch_points"],
        },
    }

    envelope = protect_report(report)
    received_report = receive_and_verify(envelope)

    crypto_view = {
        "AES-256-GCM": "Encrypted report and verified ciphertext integrity",
        "RSA-OAEP": "Protected the AES session key for the analyzer",
        "RSA-PSS": "Verified the sender's signature",
        "Report received": received_report["app"],
        "Ciphertext preview": envelope["ciphertext"][:100] + "...",
    }

    return risk_view, details, crypto_view


def run_attack_checks(app_name, purpose, requested, needed):
    _, report = make_report(app_name, purpose, requested, needed)
    original = protect_report(report)
    outcomes = []

    # Alter one byte in the encrypted report.
    changed_ciphertext = copy.deepcopy(original)
    data = bytearray(base64.b64decode(changed_ciphertext["ciphertext"]))
    data[-1] ^= 1
    changed_ciphertext["ciphertext"] = base64.b64encode(data).decode("ascii")

    try:
        receive_and_verify(changed_ciphertext)
        outcomes.append("❌ Tampered ciphertext was accepted")
    except InvalidTag:
        outcomes.append("✅ AES-GCM rejected tampered ciphertext")

    # Try to decrypt the wrapped AES key with an unrelated RSA key.
    wrong_private_key = rsa.generate_private_key(
        public_exponent=65537,
        key_size=2048
    )

    try:
        wrong_private_key.decrypt(
            base64.b64decode(original["wrapped_key"]),
            padding.OAEP(
                mgf=padding.MGF1(algorithm=hashes.SHA256()),
                algorithm=hashes.SHA256(),
                label=None
            )
        )
        outcomes.append("❌ Wrong private key was accepted")
    except ValueError:
        outcomes.append("✅ RSA-OAEP rejected the wrong private key")

    # Alter one byte in the sender's signature.
    changed_signature = copy.deepcopy(original)
    signature = bytearray(base64.b64decode(changed_signature["signature"]))
    signature[-1] ^= 1
    changed_signature["signature"] = base64.b64encode(signature).decode("ascii")

    try:
        receive_and_verify(changed_signature)
        outcomes.append("❌ Modified signature was accepted")
    except InvalidSignature:
        outcomes.append("✅ RSA-PSS rejected the modified signature")

    return "\n\n".join(outcomes)


