import base64
import json
import os
from cryptography.exceptions import InvalidSignature, InvalidTag
from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.asymmetric import padding, rsa
from cryptography.hazmat.primitives.ciphers.aead import AESGCM


# Demo keys:
# The sender signs reports with its private key.
sender_private_key = rsa.generate_private_key(
    public_exponent=65537,
    key_size=2048
)
sender_public_key = sender_private_key.public_key()

# The analyzer decrypts reports with its private key.
analyzer_private_key = rsa.generate_private_key(
    public_exponent=65537,
    key_size=2048
)
analyzer_public_key = analyzer_private_key.public_key()


def canonical_bytes(data):
    """Create a consistent byte representation of a report."""
    return json.dumps(
        data,
        sort_keys=True,
        separators=(",", ":")
    ).encode("utf-8")


def protect_report(report):
    """Sign and encrypt a report for the analyzer."""
    plaintext = canonical_bytes(report)

    # Digital signature: sender signs the report.
    signature = sender_private_key.sign(
        plaintext,
        padding.PSS(
            mgf=padding.MGF1(hashes.SHA256()),
            salt_length=padding.PSS.MAX_LENGTH
        ),
        hashes.SHA256()
    )

    # AES-256-GCM encrypts the report and detects ciphertext tampering.
    aes_key = AESGCM.generate_key(bit_length=256)
    nonce = os.urandom(12)
    ciphertext = AESGCM(aes_key).encrypt(nonce, plaintext, None)

    # RSA-OAEP encrypts the AES key for the analyzer.
    wrapped_key = analyzer_public_key.encrypt(
        aes_key,
        padding.OAEP(
            mgf=padding.MGF1(algorithm=hashes.SHA256()),
            algorithm=hashes.SHA256(),
            label=None
        )
    )

    return {
        "nonce": base64.b64encode(nonce).decode("ascii"),
        "wrapped_key": base64.b64encode(wrapped_key).decode("ascii"),
        "ciphertext": base64.b64encode(ciphertext).decode("ascii"),
        "signature": base64.b64encode(signature).decode("ascii"),
    }


def receive_and_verify(envelope):
    """Decrypt the report and verify the sender's signature."""
    nonce = base64.b64decode(envelope["nonce"])
    wrapped_key = base64.b64decode(envelope["wrapped_key"])
    ciphertext = base64.b64decode(envelope["ciphertext"])
    signature = base64.b64decode(envelope["signature"])

    # Only the analyzer's private key can recover the AES key.
    aes_key = analyzer_private_key.decrypt(
        wrapped_key,
        padding.OAEP(
            mgf=padding.MGF1(algorithm=hashes.SHA256()),
            algorithm=hashes.SHA256(),
            label=None
        )
    )

    # AES-GCM decrypts and checks whether encrypted data was changed.
    plaintext = AESGCM(aes_key).decrypt(nonce, ciphertext, None)

    # Verify that the report was signed by the sender's private key.
    sender_public_key.verify(
        signature,
        plaintext,
        padding.PSS(
            mgf=padding.MGF1(hashes.SHA256()),
            salt_length=padding.PSS.MAX_LENGTH
        ),
        hashes.SHA256()
    )

    return json.loads(plaintext.decode("utf-8"))


