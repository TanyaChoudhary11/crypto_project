# Permission sensitivity points for our classroom risk model
PERMISSION_RISK = {
    "Camera": 15,
    "Microphone": 15,
    "Location": 20,
    "Contacts": 20,
    "Photos/Storage": 12,
    "Notifications": 5,
}

# Each profile states what the fictional app does,
# what it requests, and what its stated function needs.
APP_PROFILES = {
    "Flashlight": {
        "purpose": "Turn the phone light on and off",
        "requested": {"Camera", "Location", "Contacts"},
        "needed": set(),
    },
    "Campus Map": {
        "purpose": "Show the user's position and provide routes",
        "requested": {"Location", "Notifications", "Contacts"},
        "needed": {"Location"},
    },
    "Voice Notes": {
        "purpose": "Record and replay voice notes",
        "requested": {"Microphone", "Photos/Storage", "Location"},
        "needed": {"Microphone", "Photos/Storage"},
    },
    "Video Caller": {
        "purpose": "Make video calls to selected contacts",
        "requested": {
            "Camera", "Microphone", "Contacts",
            "Notifications", "Location"
        },
        "needed": {
            "Camera", "Microphone", "Contacts", "Notifications"
        },
    },
}

def analyze_app(app_name, profile):
    requested = set(profile["requested"])
    needed = set(profile["needed"])

    unknown = requested - PERMISSION_RISK.keys()
    if unknown:
        raise ValueError(f"Unknown permissions: {sorted(unknown)}")

    excessive = requested - needed
    missing = needed - requested

    # Score = sensitivity of requested permissions
    #         + 15 points for each request beyond the stated need.
    sensitivity_points = sum(PERMISSION_RISK[p] for p in requested)
    mismatch_points = 15 * len(excessive)
    score = min(100, sensitivity_points + mismatch_points)

    if score < 25:
        level = "LOW"
    elif score < 50:
        level = "MODERATE"
    elif score < 75:
        level = "HIGH"
    else:
        level = "CRITICAL"

    return {
        "app": app_name,
        "purpose": profile["purpose"],
        "requested": requested,
        "needed": needed,
        "excessive": excessive,
        "missing": missing,
        "sensitivity_points": sensitivity_points,
        "mismatch_points": mismatch_points,
        "score": score,
        "level": level,
        "recommended": requested & needed,
    }

def show_analysis(result):
    print(f"\n{'=' * 60}")
    print(f"APP: {result['app']}")
    print(f"Stated purpose: {result['purpose']}")
    print(f"Risk level: {result['level']} ({result['score']}/100)")
    print(f"Requested: {sorted(result['requested'])}")
    print(f"Needed for stated purpose: {sorted(result['needed'])}")
    print(f"Excessive for stated purpose: {sorted(result['excessive'])}")
    print(f"Recommended least-privilege set: {sorted(result['recommended'])}")
    print(
        "Score breakdown: "
        f"{result['sensitivity_points']} sensitivity + "
        f"{result['mismatch_points']} mismatch points"
    )
    print("This is a transparent classroom risk model, not proof of malware.")

